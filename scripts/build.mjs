import { readFile, mkdir, writeFile } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const read = path => readFile(new URL(path, root), 'utf8');
const page = (await read('web/index.html')).replace(/<script type="text\/plain" id="legacy-demo-disabled">[\s\S]*?<\/script>/, '');
const assets = Object.fromEntries(await Promise.all(['app.js', 'parser.js'].map(async name => ['/' + name, await read('web/' + name)])));
const source = await read('worker/index.js');
await mkdir(new URL('dist/server/', root), { recursive: true });
await mkdir(new URL('dist/.openai/', root), { recursive: true });
await writeFile(new URL('dist/server/index.js', root), `const PAGE = ${JSON.stringify(page)};\nconst ASSETS = ${JSON.stringify(assets)};\n${source}`);
await writeFile(new URL('dist/.openai/hosting.json', root), await read('.openai/hosting.json'));
const artifact = await import(new URL('../dist/server/index.js', import.meta.url));
if (typeof artifact.default?.fetch !== 'function') throw new Error('Worker must export fetch');
console.log('Built Worker ESM with embedded page and assets.');
