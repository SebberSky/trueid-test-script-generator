import { readFile, mkdir, writeFile } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const read = path => readFile(new URL(path, root), 'utf8');
const page = (await read('web/index.html')).replace(/<script type="text\/plain" id="legacy-demo-disabled">[\s\S]*?<\/script>/, '');
const mcpDocs = await read('web/mcp-docs-v2.html');
const assets = Object.fromEntries(await Promise.all(['app.js', 'parser.js', 'media.js'].map(async name => ['/' + name, await read('web/' + name)])));
const media = (await read('worker/media.js')).replace(/^export /gm, '');
const parser = (await read('web/parser.js')).replace(/^export /gm, '');
const qa = (await read('worker/qa.js')).replace(/^export /gm, '');
const source = (await read('worker/index.js')).replace(/^import .*from '\.\/media\.js';\n/m, '').replace(/^import .*from '\.\/parser\.js';\n/m, '');
const bundledSource = source.replace(/^import .*from '\.\/qa\.js';\n/m, '');
await mkdir(new URL('dist/server/', root), { recursive: true });
await mkdir(new URL('dist/.openai/', root), { recursive: true });
await writeFile(new URL('dist/server/index.js', root), `const PAGE = ${JSON.stringify(page)};\nconst MCP_DOCS = ${JSON.stringify(mcpDocs)};\nconst ASSETS = ${JSON.stringify(assets)};\n${parser}\n${media}\n${qa}\n${bundledSource}`);
await writeFile(new URL('dist/.openai/hosting.json', root), await read('.openai/hosting.json'));
const artifact = await import(new URL('../dist/server/index.js', import.meta.url));
if (typeof artifact.default?.fetch !== 'function') throw new Error('Worker must export fetch');
console.log('Built Worker ESM with embedded page and assets.');
